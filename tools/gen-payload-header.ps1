# Embeds UserFiles/payload.js into a C++ header (as a list of raw string literals)
# that the DLL sends to KOOK pages through the DevTools protocol.
#
# The payload is split into several literals because MSVC limits a single string
# literal to 16380 bytes (error C2026).  FkoPayloadTemplate() joins them back.
#
# Usage:  powershell -ExecutionPolicy Bypass -File tools\gen-payload-header.ps1
# NOTE: keep this file ASCII-only (Windows PowerShell 5.1 reads non-BOM files as ANSI).
param(
    [string]$Payload   = (Join-Path $PSScriptRoot '..\UserFiles\payload.js'),
    [string]$Out       = (Join-Path $PSScriptRoot '..\UserFiles\kookclean_payload.h'),
    [int]$ChunkBytes   = 12000
)

$payloadPath = [System.IO.Path]::GetFullPath($Payload)
$outPath     = [System.IO.Path]::GetFullPath($Out)

$js = [System.IO.File]::ReadAllText($payloadPath)
if ($js.Contains(')FKOJS"')) {
    throw 'payload.js contains the raw string terminator, rewrite that part'
}

$utf8 = [System.Text.Encoding]::UTF8
$chunks = New-Object System.Collections.Generic.List[string]
$sb = New-Object System.Text.StringBuilder
$size = 0
foreach ($ch in $js.ToCharArray()) {
    $b = $utf8.GetByteCount([string]$ch)
    if (($size + $b) -gt $ChunkBytes) {
        $chunks.Add($sb.ToString())
        [void]$sb.Clear()
        $size = 0
    }
    [void]$sb.Append($ch)
    $size += $b
}
if ($sb.Length -gt 0) { $chunks.Add($sb.ToString()) }
if ($chunks.Count -eq 0) { $chunks.Add('') }

$body = New-Object System.Text.StringBuilder
[void]$body.AppendLine('// Generated by tools/gen-payload-header.ps1 -- do not edit.')
[void]$body.AppendLine('// Source: UserFiles/payload.js')
[void]$body.AppendLine('#pragma once')
[void]$body.AppendLine('')
[void]$body.AppendLine('#include <string>')
[void]$body.AppendLine('')
[void]$body.AppendLine('static const char* const kPayloadChunks[] = {')
foreach ($c in $chunks) {
    [void]$body.AppendLine('R"FKOJS(' + $c + ')FKOJS",')
}
[void]$body.AppendLine('};')
[void]$body.AppendLine('')
[void]$body.AppendLine(('static const unsigned int kPayloadChunkCount = {0};' -f $chunks.Count))
[void]$body.AppendLine('')
[void]$body.AppendLine('inline std::string FkoPayloadTemplate() {')
[void]$body.AppendLine('    std::string out;')
[void]$body.AppendLine('    for (unsigned int i = 0; i < kPayloadChunkCount; ++i) { out += kPayloadChunks[i]; }')
[void]$body.AppendLine('    return out;')
[void]$body.AppendLine('}')

$header = $body.ToString()
$utf8Bom = New-Object System.Text.UTF8Encoding($true)
[System.IO.File]::WriteAllText($outPath, $header, $utf8Bom)

Write-Host ("generated: {0} ({1} chars, {2} chunks)" -f $outPath, $header.Length, $chunks.Count)
